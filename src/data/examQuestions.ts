export function getExamSubmissions(): ExamSubmission[] {
  try {
    const raw = localStorage.getItem(EXAM_STORAGE_KEYS.SUBMISSIONS);
    return raw ? JSON.parse(raw) : [];
  } catch {
    return [];
  }
}

export function saveExamSubmissions(submissions: ExamSubmission[]) {
  try {
    localStorage.setItem(EXAM_STORAGE_KEYS.SUBMISSIONS, JSON.stringify(submissions));
  } catch (err) {
    console.error('Failed to save exam submissions:', err);
  }
}
